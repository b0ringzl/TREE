const assert = require('node:assert/strict');
const {chromium} = require('C:/Users/25041725G/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'msedge'});
  const page=await browser.newPage({viewport:{width:1450,height:1050}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.REVIEW_TEST_URL+'/?filter=pending');
  if(process.env.REVIEW_READ_ONLY==='1'){
    await page.waitForFunction(()=>document.querySelector('#photo').naturalWidth>10);
    assert.equal(await page.locator('#error').isVisible(),false);
    const real=await page.evaluate(()=>fetch('/api/items').then(r=>r.json()));
    assert(real.items.length>0);
    assert(real.items.every(i=>i.decision===null));
    await page.screenshot({path:process.env.REVIEW_TEST_SCREENSHOT,fullPage:true});
    console.log(JSON.stringify({passed:true,readOnly:true,items:real.items.length,screenshot:process.env.REVIEW_TEST_SCREENSHOT}));
    await browser.close();
    return;
  }
  await page.waitForFunction(()=>document.querySelector('#position').textContent==='1 / 3');
  assert.match(await page.locator('#progress').textContent(),/0 \/ 3/);
  assert.equal(await page.locator('#reviewNote').isVisible(),true);
  assert.match(await page.locator('#reviewNoteText').textContent(),/<img src=x/);
  assert.equal(await page.locator('#reviewNoteText img').count(),0);
  await page.locator('#note').fill('A typed note must not trigger shortcuts: a n u x.');
  await page.locator('#note').press('a');
  assert.match(await page.locator('#progress').textContent(),/0 \/ 3/);
  await page.locator('h1').click();
  await page.keyboard.press('a');
  await page.waitForFunction(()=>document.querySelector('#progress').textContent.startsWith('1 / 3'));
  await page.waitForFunction(()=>document.querySelector('#position').textContent==='1 / 2');
  assert.equal(await page.locator('#reviewNote').isVisible(),false);
  let data=await page.evaluate(()=>fetch('/api/items').then(r=>r.json()));
  assert.equal(data.items[0].decision.decision,'aquilaria');
  assert.match(data.items[0].decision.note,/typed note/);
  assert.equal(data.items[0].source_species,'Source species stays unchanged');
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#position').textContent(),'2 / 2');
  await page.keyboard.press('ArrowLeft');
  await page.keyboard.press('n');
  await page.waitForFunction(()=>document.querySelector('#progress').textContent.startsWith('2 / 3'));
  await page.keyboard.press('u');
  await page.waitForFunction(()=>document.querySelector('#progress').textContent.startsWith('3 / 3'));
  assert.equal(await page.locator('#empty').isVisible(),true);
  await page.locator('#undo').click();
  await page.waitForFunction(()=>document.querySelector('#progress').textContent.startsWith('2 / 3'));
  await page.locator('#statusFilter').selectOption('all');
  await page.locator('#sourceDetails').waitFor({state:'attached'});
  data=await page.evaluate(()=>fetch('/api/export').then(r=>r.json()));
  assert.equal(data.decisions.length,2);
  assert.equal(data.history.length,4);
  assert.equal(data.decisions[1].human_review.decision,'not_aquilaria');
  assert.equal(errors.length,0,errors.join('\n'));
  await page.screenshot({path:process.env.REVIEW_TEST_SCREENSHOT,fullPage:true});
  console.log(JSON.stringify({passed:true,checks:['keyboard save','text field shortcut exclusion','save-next','navigation','empty pending state','undo','export','source label preserved','no browser exceptions'],screenshot:process.env.REVIEW_TEST_SCREENSHOT}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
